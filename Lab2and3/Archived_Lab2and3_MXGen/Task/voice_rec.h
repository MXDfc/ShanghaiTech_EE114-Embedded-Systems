#ifndef _VOICE_REC_H
#define _VOICE_REC_H

/*
 * voice_rec.h — 语音识别/播报模块接口
 *
 * 硬件说明：
 *   本模块通过 HAL I2C2（PB10=SCL，PB11=SDA，400 kHz）与语音模块通信。
 *   语音模块 I2C 7-bit 地址：0x34
 *   - 寄存器 0x6E：写入 [cmd, idNum] 触发播报
 *   - 寄存器 0x64：读取当前识别结果
 *
 * 协议说明（源自软件 IIC 参考例程逆向分析）：
 *   播报命令（Asr_Speak）：
 *     START → 写地址(0x34) → 寄存器(0x6E) → cmd → idNum → STOP
 *     cmd = ASR_CMD_COMMAND  (0x00)：播放指令音（指令模式）
 *     cmd = ASR_CMD_ANNOUNCE (0xFF)：播放报告音（播报模式）
 *
 *   读取识别结果（Asr_GetResult）：
 *     START → 写地址(0x34) → 寄存器(0x64) → START → 读地址(0x34) → 读1字节 → STOP
 *     返回值为识别到的词条 ID，0 表示无识别结果或通信失败
 */

#include "main.h"
#include <stdint.h>

/* -----------------------------------------------------------------------
 * 播报命令类型
 *   ASR_CMD_COMMAND  : 指令模式，播放预设指令音
 *   ASR_CMD_ANNOUNCE : 播报模式，播放预设报告音
 * ----------------------------------------------------------------------- */
#define ASR_CMD_COMMAND   0x00U
#define ASR_CMD_ANNOUNCE  0xFFU

/* -----------------------------------------------------------------------
 * ASR_Init
 *   初始化语音模块（当前仅做延时等待模块上电稳定）。
 *   调用时机：在 MX_I2C2_Init() 之后调用。
 * ----------------------------------------------------------------------- */
void ASR_Init(void);

/* -----------------------------------------------------------------------
 * ASR_Speak
 *   向语音模块发送播报命令。
 *
 *   参数：
 *     cmd   — 命令类型，取值 ASR_CMD_COMMAND 或 ASR_CMD_ANNOUNCE
 *     idNum — 词条编号（从 1 开始，具体编号参考语音模块配置表）
 *
 *   返回值：
 *     HAL_OK    : 发送成功
 *     HAL_ERROR : I2C 通信失败
 *
 *   注意：函数内部包含 20 ms 延时，等待模块处理命令，
 *         请勿在对实时性要求极高的上下文中调用。
 * ----------------------------------------------------------------------- */
HAL_StatusTypeDef ASR_Speak(uint8_t cmd, uint8_t idNum);

/* -----------------------------------------------------------------------
 * ASR_GetResult
 *   读取语音模块当前的识别结果。
 *
 *   返回值：
 *     > 0 : 识别到的词条 ID
 *       0 : 无识别结果，或 I2C 通信失败
 *
 *   注意：函数内部包含 20 ms 延时，建议以轮询方式在主循环中周期调用，
 *         而非高频连续调用。
 * ----------------------------------------------------------------------- */
uint8_t ASR_GetResult(void);

#endif /* _VOICE_REC_H */
